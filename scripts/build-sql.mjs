// Joins supabase/migrations/*.sql (in order) into supabase/all-migrations.sql so the whole database can be created with ONE paste.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const dir = new URL("../supabase/migrations/", import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const out = files.map((f) => `-- ═══════════ ${f} ═══════════\n${readFileSync(new URL(f, dir), "utf8")}`).join("\n");
writeFileSync(new URL("../supabase/all-migrations.sql", import.meta.url), `-- Hontrix-PDTR: complete database setup (${files.length} migrations). Generated by scripts/build-sql.mjs — do not edit by hand.\n${out}`);
console.log(`Wrote supabase/all-migrations.sql from ${files.length} files`);
